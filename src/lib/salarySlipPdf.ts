import { buildReport, downloadReport } from '@/lib/pdfReport';

const money = (n: number | string | null | undefined) => `₹${Number(n || 0).toLocaleString('en-IN', { maximumFractionDigits: 2 })}`;

export const downloadSalarySlip = (record: any, admin: any, generatedBy?: string) => {
  const month = new Date(record.salary_month);
  const earnings = Number(record.basic_salary || 0) + Number(record.hra || 0) + Number(record.allowances || 0) + Number(record.bonus || 0);
  const totalDeductions = Number(record.deductions || 0) + Number(record.tax || 0);
  const doc = buildReport({
    title: 'Salary Slip',
    subtitle: `${admin?.name || record.admin?.name || 'Admin'} · ${month.toLocaleString('en-IN', { month: 'long', year: 'numeric' })}`,
    range: { from: month, to: month },
    generatedBy,
    theme: 'classic',
    kpis: [
      { label: 'Gross Salary', value: money(record.gross_salary) },
      { label: 'Paid Days', value: `${record.paid_days || 0}/${record.working_days || 0}` },
      { label: 'Deductions', value: money(totalDeductions) },
      { label: 'Net Pay', value: money(record.net_salary) },
    ],
    sections: [
      {
        title: 'Employee Details',
        head: [['Field', 'Value']],
        body: [
          ['Name', admin?.name || record.admin?.name || '—'],
          ['Email', admin?.email || record.admin?.email || '—'],
          ['Role', (admin?.role || record.admin?.role || '—').replace('_', ' ')],
          ['Salary Month', month.toLocaleString('en-IN', { month: 'long', year: 'numeric' })],
          ['Status', String(record.status || 'draft').toUpperCase()],
          ['Payment Date', record.payment_date || '—'],
        ],
      },
      {
        title: 'Salary Breakdown',
        head: [['Component', 'Amount']],
        body: [
          ['Basic Salary', money(record.basic_salary)],
          ['HRA', money(record.hra)],
          ['Allowances', money(record.allowances)],
          ['Bonus', money(record.bonus)],
          ['Total Earnings', money(earnings)],
          ['Deductions', money(record.deductions)],
          ['Tax', money(record.tax)],
          ['Net Salary Payable', money(record.net_salary)],
        ],
      },
      {
        title: 'Notes & Approval',
        head: [['Field', 'Value']],
        body: [
          ['Notes', record.notes || '—'],
          ['Generated By', generatedBy || 'Ergon Admin'],
          ['Confidentiality', 'This digitally generated salary slip is confidential.'],
        ],
      },
    ],
  });
  downloadReport(doc, `salary-slip-${(admin?.name || 'admin').toLowerCase().replace(/\s+/g, '-')}-${record.salary_month}`);
};
